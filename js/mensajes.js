function mensajeFinal(nota) {
  if (nota >= 9.5) return "¡Leyenda absoluta! 🌟";
  if (nota >= 9) return "¡Sobresaliente de brillo! ✨";
  if (nota >= 7) return "¡Muy bien, sigue así! 💖";
  if (nota >= 5) return "¡Aprobado, bien hecho! 🎉";
  if (nota >= 4) return "Casi casi, ¡ánimo! 💪";
  return "Hay que remontar, pero se puede 🚀";
}
